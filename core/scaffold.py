#!/usr/bin/env python3
"""
Cog: Configuration Scaffolding Engine (scaffold.py)
Automates project onboarding by scanning repositories and generating
domain-structured cog.conf and cog.ignore configuration files.
"""

import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

CORE_DIR = Path(__file__).resolve().parent
if str(CORE_DIR) not in sys.path:
    sys.path.insert(0, str(CORE_DIR))

from scanner import RepoScanner
from ignore_matcher import IgnoreFilter


class ConfigScaffolder:
    """
    Automates the creation of context/conf/cog.conf and context/conf/cog.ignore.
    """

    DEFAULT_IGNORE_TEMPLATE = """# ==============================================================================
# Cog Ignore Configuration File (cog.ignore)
# Declares path patterns to exclude from Cog scanning and context generation.
# Syntax follows standard .gitignore format (*, **, ?, leading/trailing slashes).
# ==============================================================================

# Git & Cog internals
.git/
.cog/

# Vivado / Vitis / EDA Compilation & Simulation Artifacts
**/.runs/
**/.cache/
**/.sim/
**/.hw/
**/.ip_user_files/
**/*.jou
**/*.log
**/*.str
**/*.pb
**/*.dcp
**/*.bit
**/*.bin
**/*.hwh
**/*.gen/

# Python & C/C++ Build Artifacts
**/__pycache__/
**/*.pyc
**/*.pyo
**/*.pyd
.venv/
venv/
*.egg-info/
dist/
build/
**/*.o
**/*.a
**/*.so
**/*.dylib
**/*.dll

# OS Metadata
.DS_Store
Thumbs.db
"""

    SECTION_HEADERS = {
        "documentation": ("📄 Documentation & Project Manifests", "# Readme, licenses, and architecture docs"),
        "build": ("⚙️  Build Systems, TCL & Project Scripts", "# Hog configs, build automation, Makefiles, TCL scripts"),
        "bd": ("🧩 Hardware - Vivado Block Designs (.bd)", "# Custom IP blocks, interconnects, and memory maps"),
        "constraints": ("📌 Hardware - Constraints (.xdc)", "# Timing constraints and physical I/O pin assignments"),
        "rtl": ("⚡ Hardware - RTL Modules (VHDL / Verilog / SystemVerilog)", "# Custom registers, datapaths, and FSM cores"),
        "software": ("🐍 Software Drivers, APIs & Host Utilities", "# Python overlays, driver libraries, C/C++ bindings"),
        "notebooks": ("📓 Jupyter Notebooks & Interactive Workflows", "# Interactive tutorial notebooks and hardware tests"),
    }

    def __init__(self, repo_root: Path, conf_dir: Optional[Path] = None):
        self.repo_root = repo_root.resolve()
        self.conf_dir = conf_dir.resolve() if conf_dir else (self.repo_root / "context" / "conf")

    def scaffold(self, force: bool = False) -> Tuple[bool, Path, Path, Dict[str, List[str]]]:
        """
        Scans repository and creates cog.conf and cog.ignore inside context/conf/.
        Returns (success_flag, cog_conf_path, cog_ignore_path, scan_results).
        """
        self.conf_dir.mkdir(parents=True, exist_ok=True)
        cog_conf_path = self.conf_dir / "cog.conf"
        cog_ignore_path = self.conf_dir / "cog.ignore"

        # Prevent accidental overwrite unless forced
        if cog_conf_path.is_file() and not force:
            return False, cog_conf_path, cog_ignore_path, {}

        # 1. Create cog.ignore if missing
        if not cog_ignore_path.is_file() or force:
            with open(cog_ignore_path, "w", encoding="utf-8") as f:
                f.write(self.DEFAULT_IGNORE_TEMPLATE)

        # 2. Run repository scanner
        ignore_filter = IgnoreFilter(self.repo_root, custom_ignore_path=cog_ignore_path)
        scanner = RepoScanner(self.repo_root, ignore_filter=ignore_filter)
        scan_results = scanner.scan()

        # 3. Generate structured cog.conf content
        lines = [
            "# ==============================================================================",
            "# Cog Configuration File (cog.conf)",
            "# Auto-generated by './Cog/Ctx init'",
            "# ==============================================================================",
            "",
            "OUTPUT: context/repo_summary.txt",
            "",
        ]

        for domain, (header_title, header_desc) in self.SECTION_HEADERS.items():
            files = scan_results.get(domain, [])
            lines.append("# " + "=" * 76)
            lines.append(f"# {header_title}")
            lines.append(f"# {header_desc}")
            lines.append("# " + "=" * 76)

            if files:
                for file_path in files:
                    lines.append(file_path)
            else:
                lines.append(f"# (No {domain} files detected)")
            lines.append("")

        with open(cog_conf_path, "w", encoding="utf-8") as f:
            f.write("\n".join(lines))

        return True, cog_conf_path, cog_ignore_path, scan_results